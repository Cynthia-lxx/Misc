def load_json(path: Path):
    with path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


def resolve_theme(scheme: dict, theme_dir: Path, cache: dict, fallback_id: str) -> dict:
    """Load a theme file, following `tokensFrom` inheritance and merging overrides."""
    theme_id = scheme["id"]
    theme_path = theme_dir / f"{theme_id}.json"

    if theme_path.is_file():
        data = load_json(theme_path)
    else:
        data = {"id": theme_id, "label": theme_id.title(), "overrides": {}}

    parent_id = data.get("tokensFrom")
    if parent_id:
        if parent_id not in cache:
            parent_scheme = next((s for s in cache["__schemes__"] if s["id"] == parent_id), None)
            if parent_scheme is None:
                raise ValueError(f"theme {theme_id}: tokensFrom '{parent_id}' not found")
            cache[parent_id] = resolve_theme(parent_scheme, theme_dir, cache, fallback_id)
        data = dict(data)
        data["tokens"] = cache[parent_id]["tokens"]

    if "tokens" not in data:
        if fallback_id not in cache:
            fallback_scheme = next((s for s in cache["__schemes__"] if s["id"] == fallback_id), None)
            cache[fallback_id] = resolve_theme(fallback_scheme, theme_dir, cache, fallback_id)
        data["tokens"] = cache[fallback_id]["tokens"]

    file_hue = data.get("hue")
    data["hue"] = int(scheme["hue"])
    data["_hueConflict"] = file_hue is not None and int(file_hue) != data["hue"]
    return data


def hsl(hue: int, pair) -> str:
    if not isinstance(pair, (list, tuple)) or len(pair) != 2:
        raise ValueError(f"token must be [saturation, lightness], got {pair!r}")
    s, l = float(pair[0]), float(pair[1])
    if not (0.0 <= s <= 1.0 and 0.0 <= l <= 1.0):
        raise ValueError(f"token out of range: {pair!r}")
    return f"hsl({hue} {round(s * 100, 4)}% {round(l * 100, 4)}%)"


def theme_block(selector: str, theme: dict, aliases: dict) -> str:
    lines = [selector + " {", f"  --theme-hue: {theme['hue']};"]
    for name, pair in theme["tokens"].items():
        lines.append(f"  {name}: {hsl(theme['hue'], pair)};")
    for name, value in aliases.items():
        lines.append(f"  {name}: {value};")
    for name, value in theme.get("overrides", {}).items():
        lines.append(f"  {name}: {value};")
    lines.append("}")
    return "\n".join(lines)


def compile_theme_css(index: dict, themes: dict) -> str:
    blocks = [
        LICENCE_HEADER,
        "/* Generated theme layer: one block per scheme + default :root block. */",
        "/* Source: OverlayColourScheme.cs / OverlayColourProvider.cs (MIT). */",
        "",
        theme_block(":root", themes[index["default"]], index["aliases"]),
        "",
    ]
    for scheme in index["schemes"]:
        blocks.append(theme_block(f"[data-theme=\"{scheme['id']}\"]", themes[scheme["id"]], index["aliases"]))
        blocks.append("")
    return "\n".join(blocks)


def validate(root: Path, manifest: dict, settings: dict, index: dict, i18n: dict, themes: dict) -> list:
    problems = []
    setting_ids = {item["id"] for item in settings["settings"]}

    for comp in manifest["components"]:
        cid = comp["id"]
        for kind, rel in comp["files"].items():
            if not (root / rel).is_file():
                problems.append(f"component {cid}: missing {kind} file {rel}")
        if any(word in cid.lower() for word in BANNED_BRAND_WORDS):
            problems.append(f"component {cid}: banned brand word in id")
        for rel in comp["files"].values():
            if any(word in rel.lower() for word in BANNED_BRAND_WORDS):
                problems.append(f"component {cid}: banned brand word in path {rel}")
        for sid in comp.get("settings", []):
            if sid not in setting_ids:
                problems.append(f"component {cid}: unknown setting id {sid}")
        for key in comp.get("i18nKeys", []):
            for lang, pack in i18n.items():
                if key not in pack:
                    problems.append(f"component {cid}: i18n key {key} missing in {lang}.json")

    referenced = [
        manifest["css"]["tokens"],
        manifest["settings"],
        manifest["themes"]["index"],
        manifest["assembly"]["script"],
        "00-overview/LICENSE-MIT.txt",
    ]
    referenced += manifest.get("extraFiles", [])
    referenced += manifest.get("extraCss", [])
    referenced += [manifest.get("demoFragment"), manifest.get("navigationDemoFragment")]
    preview = manifest.get("preview", {})
    referenced += [preview.get("shell"), preview.get("server")]
    for rel in referenced:
        if rel and not (root / rel).is_file():
            problems.append(f"missing referenced file {rel}")

    preview_dir = root / "10-templates/preview"
    for name in ("preview.css", "app.js", "views.js", "view-overview.js", "view-theme.js",
                 "view-components.js", "view-motion.js", "view-layers.js", "view-effects.js", "view-data.js"):
        if not (preview_dir / name).is_file():
            problems.append(f"missing preview module {name}")

    for rel in manifest.get("extraFiles", []):
        if any(word in rel.lower() for word in BANNED_BRAND_WORDS):
            problems.append(f"banned brand word in extra file path {rel}")

    for scheme in index["schemes"]:
        tid = scheme["id"]
        if tid not in themes:
            problems.append(f"scheme {tid}: no resolved theme")
            continue
        if not (0 <= int(scheme["hue"]) <= 360):
            problems.append(f"scheme {tid}: hue out of range")
        if themes[tid].get("_hueConflict"):
            problems.append(f"scheme {tid}: hue in theme file differs from index.json")
        for name, pair in themes[tid]["tokens"].items():
            try:
                hsl(int(scheme["hue"]), pair)
            except ValueError as exc:
                problems.append(f"scheme {tid} token {name}: {exc}")

    if index["default"] not in themes:
        problems.append(f"default theme {index['default']} not found")
    if manifest["themes"]["default"] != index["default"]:
        problems.append("default theme differs between ui-manifest.json and themes/index.json")
    return problems


def build_html(root: Path, manifest: dict, index: dict, themes: dict,
               lang: str, theme: str, languages: list) -> str:
    theme_options = "\n".join(
        f'        <option value="{tid}"{" selected" if tid == theme else ""}>{themes[tid]["label"]}</option>'
        for tid in [s["id"] for s in index["schemes"]]
    )
    lang_options = "\n".join(
        f'        <option value="{code}"{" selected" if code == lang else ""}>{code}</option>'
        for code in languages
    )
    extra_css = "\n".join(
        f'  <link rel="stylesheet" href="{rel}">' for rel in manifest.get("extraCss", [])
    )
    fragment = (root / manifest["demoFragment"]).read_text(encoding="utf-8")
    menu_fragment = (root / manifest["navigationDemoFragment"]).read_text(encoding="utf-8")

    return (HTML_TEMPLATE
            .replace("__LANG__", lang)
            .replace("__THEME__", theme)
            .replace("__THEME_OPTIONS__", theme_options)
            .replace("__LANG_OPTIONS__", lang_options)
            .replace("__EXTRA_CSS__", extra_css)
            .replace("__视觉效果_DEMO__", menu_fragment + "\n\n" + fragment))


def build_preview_html(root: Path, manifest: dict, index: dict, themes: dict,
                       lang: str, theme: str, languages: list, config: dict) -> str:
    """Generate dist/preview.html from the preview application shell."""
    shell = (root / manifest["preview"]["shell"]).read_text(encoding="utf-8")
    # 预览工具栏用库自己的 ui-dropdown（option 是 ui-option 而非原生 option）
    theme_ui_options = "\n".join(
        f'            <ui-option value="{tid}" label="{themes[tid]["label"]}"></ui-option>'
        for tid in [s["id"] for s in index["schemes"]]
    )
    lang_ui_options = "\n".join(
        f'            <ui-option value="{code}" label="{code}"></ui-option>'
        for code in languages
    )
    extra_css = "\n".join(
        f'  <link rel="stylesheet" href="{rel}">' for rel in manifest.get("extraCss", [])
    )
    return (shell
            .replace("__THEME_UI_OPTIONS__", theme_ui_options)
            .replace("__LANG_UI_OPTIONS__", lang_ui_options)
            .replace("__EXTRA_CSS__", extra_css)
            .replace("__APP_CONFIG__", json.dumps(config, ensure_ascii=False))
            .replace("__BUILD__", config["build"])
            .replace("__LANG__", lang)
            .replace("__THEME__", theme))


def assemble(root: Path, out: Path, theme: str, lang: str, check_only: bool) -> dict:
    manifest = load_json(root / "00-overview/ui-manifest.json")
    settings = load_json(root / manifest["settings"])
    index = load_json(root / manifest["themes"]["index"])

    i18n_dir = root / manifest["i18n"]["dir"]
    languages = sorted(p.stem for p in i18n_dir.glob("*.json"))
    i18n = {code: load_json(i18n_dir / f"{code}.json") for code in languages}

    theme_dir = root / manifest["themes"]["dir"]
    cache = {"__schemes__": index["schemes"]}
    themes = {s["id"]: resolve_theme(s, theme_dir, cache, index["fallbackTheme"])
              for s in index["schemes"]}

    problems = validate(root, manifest, settings, index, i18n, themes)
    if problems:
        raise ValueError("validation failed:\n  - " + "\n  - ".join(problems))
    if theme not in themes:
        raise ValueError(f"unknown theme {theme!r}; choose from {sorted(themes)}")
    if lang not in i18n:
        raise ValueError(f"unknown language {lang!r}; choose from {languages}")

    summary = {
        "themes": sorted(themes),
        "languages": languages,
        "components": [c["id"] for c in manifest["components"]],
        "settings": len(settings["settings"]),
        "i18nKeys": len(i18n[lang]),
        "motion": manifest.get("motion", {}).get("data"),
        "vfxFiles": len(manifest.get("extraFiles", [])),
        "preview": manifest.get("preview", {}).get("output"),
        "previewViews": len(manifest.get("preview", {}).get("views", [])),
        "validation": "ok",
    }
    if check_only:
        return summary

    out.mkdir(parents=True, exist_ok=True)
    (out / "components").mkdir(exist_ok=True)
    (out / "i18n").mkdir(exist_ok=True)

    shutil.copy2(root / manifest["css"]["tokens"], out / "tokens.css")
    (out / "themes.css").write_text(compile_theme_css(index, themes), encoding="utf-8")
    (out / "settings.json").write_text(json.dumps(settings, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out / "LICENSE-MIT.txt").write_bytes((root / "00-overview/LICENSE-MIT.txt").read_bytes())
    shutil.copy2(root / "00-overview/licence-audit.json", out / "licence-audit.json")

    for code, pack in i18n.items():
        (out / "i18n" / f"{code}.json").write_text(
            json.dumps(pack, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    for comp in manifest["components"]:
        dest = out / "components" / comp["id"]
        dest.mkdir(parents=True, exist_ok=True)
        for rel in comp["files"].values():
            shutil.copy2(root / rel, dest / Path(rel).name)

    # Keep the original relative layout so ES module relative imports keep working.
    for rel in manifest.get("extraFiles", []):
        dest = out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(root / rel, dest)

    (out / "index.html").write_text(
        build_html(root, manifest, index, themes, lang, theme, languages), encoding="utf-8")

    # ---- data surfaces for the preview site (static-mode API fallbacks) ----
    shutil.copy2(root / "00-overview/ui-manifest.json", out / "manifest.json")
    (out / "themes").mkdir(exist_ok=True)
    for theme_file in (root / manifest["themes"]["dir"]).glob("*.json"):
        shutil.copy2(theme_file, out / "themes" / theme_file.name)

    # ---- full preview site: shell -> preview.html, modules -> preview/ ----
    preview_src = root / "10-templates/preview"
    preview_out = out / "preview"
    preview_out.mkdir(parents=True, exist_ok=True)
    for source in sorted(preview_src.iterdir()):
        if source.is_file() and source.name != "shell.html":
            shutil.copy2(source, preview_out / source.name)
    shutil.copy2(root / manifest["preview"]["server"], out / "preview_server.py")

    staged = sorted(str(p.relative_to(out)).replace("\\", "/") for p in out.rglob("*") if p.is_file())
    preview_config = {
        "theme": theme,
        "lang": lang,
        "themes": [s["id"] for s in index["schemes"]],
        "languages": languages,
        "build": "2026-11-13",
        "files": sorted(set(staged + ["preview.html"])),
    }
    (out / "preview.html").write_text(
        build_preview_html(root, manifest, index, themes, lang, theme, languages, preview_config),
        encoding="utf-8")
    summary["output"] = str(out)
    summary["generatedFiles"] = sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())
    return summary


def main(argv=None) -> int:
    default_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description="Assemble the UI reference kit (Python 3).")
    parser.add_argument("--root", type=Path, default=default_root, help="UIReference root directory")
    parser.add_argument("--out", type=Path, default=None, help="output directory (default: <root>/dist)")
    parser.add_argument("--theme", default="blue", help="default theme id")
    parser.add_argument("--lang", default="en", help="default language code")
    parser.add_argument("--check", action="store_true", help="validate inputs only, write nothing")
    parser.add_argument("--clean", action="store_true", help="remove the generated dist directory before assembling")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    out = (args.out or (root / "dist")).resolve()
    if args.clean and not args.check and out.is_dir() and out.name == "dist":
        # Remove generated files explicitly; some environments wrap shutil.rmtree
        # with a trash/recycle shim that does not work reliably on this path.
        for path in sorted(out.rglob("*"), key=lambda p: len(p.parts), reverse=True):
            try:
                if path.is_file():
                    path.unlink()
                elif path.is_dir():
                    path.rmdir()
            except OSError:
                pass  # some environments wrap rmdir with a trash shim
        try:
            out.rmdir()
        except OSError:
            pass
    try:
        result = assemble(root, out, args.theme, args.lang, args.check)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"[assemble] ERROR: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
