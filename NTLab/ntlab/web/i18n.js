let lang = localStorage.getItem("ntlab-lang") === "zh" ? "zh" : "en";

/* 大页面（pe/objdir/resedit/playground/imgedit）的条目直接以**中文原文作 key**，
 * 词典只需维护 en 映射；这里给 zh 自动补恒等映射（t() 回退亦如此），
 * 并让 UIReference.i18n 在 zh 下也能查到组件自解析所需的键。 */
for (const k of Object.keys(DICTS.en)) {
  if (!(k in DICTS.zh)) DICTS.zh[k] = k;
}

export function t(key, params) {
  let s = DICTS[lang][key] ?? DICTS.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function getLang() {
  return lang;
}

/** 切换语言：更新 UIReference 全局词典 → 刷 [data-i18n-key] → 派发组件级刷新事件。 */
export function setLang(next) {
  if (!DICTS[next] || next === lang) return lang;
  lang = next;
  localStorage.setItem("ntlab-lang", lang);
  globalThis.UIReference = { ...(globalThis.UIReference ?? {}), i18n: DICTS[lang] };
  applyDom();
  document.dispatchEvent(new CustomEvent("ui-i18n-change"));
  return lang;
}

/** 刷新 i18n 标记的 DOM：
 * - [data-i18n-key] → textContent（有 Shadow Root 的组件自解析，跳过）
 * - [data-i18n-ph]  → placeholder（输入框）
 * - [data-i18n-title] → title 属性 */
export function applyDom(root = document) {
  root.querySelectorAll("[data-i18n-key]").forEach((el) => {
    if (el.shadowRoot) return;   // ui-button/ui-tabs 等组件按 ui-i18n-change 自刷新
    el.textContent = t(el.dataset.i18nKey);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPh));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
}

globalThis.UIReference = { ...(globalThis.UIReference ?? {}), i18n: DICTS[lang] };
